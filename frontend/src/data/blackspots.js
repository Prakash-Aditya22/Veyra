// Distribute `total` incidents across 24 hours following a profile, with a
// small seeded jitter so no two clusters share an identical histogram.
function buildHourly(total, profileKey, seed) {
  const profile = PROFILES[profileKey];
  const rand = seeded(seed);
  const jittered = profile.map((w) => w * (0.78 + rand() * 0.44));
  const sum = jittered.reduce((a, b) => a + b, 0);
  const raw = jittered.map((w) => (w / sum) * total);

  // Largest-remainder rounding so the histogram sums back to `total` exactly.
  const floors = raw.map(Math.floor);
  let remainder = total - floors.reduce((a, b) => a + b, 0);
  const order = raw
    .map((v, i) => ({ i, frac: v - Math.floor(v) }))
    .sort((a, b) => b.frac - a.frac);
  for (let k = 0; k < remainder; k += 1) floors[order[k % 24].i] += 1;

  return floors.map((count, hour) => ({ hour, count }));
}


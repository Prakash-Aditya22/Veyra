"""Write the v2 release manifest and the machine-readable integration schema.

    .venv/Scripts/python ml/audit/release_manifest.py

Reads the existing outputs; changes none of them. Writes two NEW files beside them:
  data/v2/release_manifest_v2.json   which files form the release, their role (required /
                                     optional / demo / research), hashes, row counts, version,
                                     training and forecast periods, timestamps and inputs
  data/v2/integration_schema_v2.json field-level contract (blackspot/contract.py: spec())

The v2 forecast step records no generation timestamp, so `outputs_generated_at` is the file
modification time of road_segments_ranked_v2.csv, and is labelled as such.
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from blackspot import contract  # noqa: E402
from blackspot.config import BACKEND_DATA, OUTPUTS, RAW  # noqa: E402
from blackspot.features import FORECAST_CUTOFF, HOLDOUT_CUTOFF, Fold  # noqa: E402
from blackspot.io_utils import file_hash, write_json  # noqa: E402

V2 = BACKEND_DATA / "v2"
FORECAST_CMD = ".venv/Scripts/python ml/pipeline.py forecast"

# (path relative to data/v2, role, format, purpose, relation to existing artefacts, regenerated by, consumer)
FILES = [
    ("road_segments_ranked_v2.csv", "required", "CSV, UTF-8, header, comma",
     "every scored segment in the national top 50,000 plus every segment with >= 6 collisions in 2023-25; one row per segment",
     "extends data/road_segments_ranked.csv (v1 columns first, same order) - new segment IDs", FORECAST_CMD,
     "backend: load into PostgreSQL/PostGIS (road_segment_v2)"),
    ("road_segments_meta_v2.json", "required", "JSON object", "version, frozen-spec hash, periods, column notes",
     "extends data/road_segments_meta.json", FORECAST_CMD, "backend: store with the load; check score_version"),
    ("road_segments_top500_v2.json", "optional", "JSON array of row objects (same fields as the CSV, full precision)",
     "top 500 for serving before the database exists", "extends data/road_segments_top500.json", FORECAST_CMD,
     "backend/frontend: static fallback"),
    ("road_segments_top5000_v2.geojson", "optional", "GeoJSON FeatureCollection (RFC 7946, WGS84 lon/lat)",
     "real OS Open Roads centreline geometry for the top 5,000", "new in v2 (v1 had midpoints only)", FORECAST_CMD,
     "backend: segment geometry table; frontend: lines"),
    ("extensions/segment_explanations_v2.csv", "optional", "CSV, 5 rows per segment",
     "top-5 TreeSHAP attributions of the production model per exported segment", "new, additive",
     ".venv/Scripts/python ml/experiments/explain_blackspot.py", "backend: segment_explanation_v2 table"),
    ("extensions/segment_explanations_top5000_v2.json", "optional", "JSON object keyed by segment_id",
     "explanations for the 5,000 mapped segments, with group factors", "new, additive",
     ".venv/Scripts/python ml/experiments/explain_blackspot.py", "map/frontend"),
    ("extensions/segment_stability_v2.csv", "optional", "CSV, 1 row per segment",
     "rank ranges and top-k frequencies across refits; window range; simultaneous drop-one rank", "new, additive",
     ".venv/Scripts/python ml/experiments/ranking_stability.py --boot 20 --seeds 5", "backend: segment_stability_v2 table"),
    ("extensions/segment_single_event_sensitivity_v2.csv", "optional", "CSV, top 1,000",
     "forecast and rank without the segment's largest collision, one-at-a-time and simultaneous", "new, additive (Phase 3)",
     ".venv/Scripts/python ml/experiments/single_event_case.py", "backend: optional warning text"),
]
DOCS = ["README.md", "INTEGRATION_CONTRACT.md", "extensions/README.md"]
NOT_FOR_LOADING = {
    "ml/outputs/road_segments_v2_full.parquet": "national table (1.83 M rows), regenerable, gitignored; research and audits",
    "ml/outputs/explainability/": "saved production model and SHAP research outputs",
    "ml/reports/": "research reports and evidence tables (historical windows, stability, audits)",
    "ml/demo/*.html": "demo maps (reference implementation of the UI rules, not an API)",
    "ml/tests/fixtures/integration/": "small test fixture, a subset of this release",
    "data/road_segments_*": "v1 outputs (superseded, kept for compatibility)",
}


def rows(path: Path) -> int | None:
    if path.suffix == ".csv":
        with open(path, "rb") as fh:
            return sum(1 for _ in fh) - 1
    if path.suffix in (".json", ".geojson"):
        d = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(d, list):
            return len(d)
        if "features" in d:
            return len(d["features"])
        if "segments" in d:
            return len(d["segments"])
    return None


def iso(ts: float) -> str:
    return dt.datetime.fromtimestamp(ts, dt.timezone.utc).isoformat(timespec="seconds")


def main() -> int:
    meta = json.loads((V2 / "road_segments_meta_v2.json").read_text(encoding="utf-8"))
    spec = json.loads((OUTPUTS / "frozen_spec.json").read_text(encoding="utf-8"))
    prod, hold = Fold(FORECAST_CUTOFF).describe(), Fold(HOLDOUT_CUTOFF).describe()
    files = []
    for rel, role, fmt, purpose, relation, regen, consumer in FILES:
        p = V2 / rel
        if not p.exists():
            files.append({"path": f"data/v2/{rel}", "role": role, "present": False})
            continue
        files.append({"path": f"data/v2/{rel}", "role": role, "present": True, "format": fmt, "purpose": purpose,
                      "relation": relation, "regenerate": regen, "consumer": consumer, "rows": rows(p),
                      "bytes": p.stat().st_size, "sha256": file_hash(p), "modified_utc": iso(p.stat().st_mtime)})
    model_file = OUTPUTS / "explainability" / "production_lgbm.txt"
    raw = {}
    if (RAW / "manifest.json").exists():
        m = json.loads((RAW / "manifest.json").read_text(encoding="utf-8"))
        raw = {k: {"url": v.get("url"), "sha256": v.get("sha256"), "downloaded_utc": v.get("downloaded_utc")}
               for k, v in m.items() if k in ("os_open_roads", "dft_aadf", "stats19_casualty_all", "stats19_data_guide_2025")
               or k.startswith("stats19_collision_")}
    ranked = V2 / "road_segments_ranked_v2.csv"
    manifest = {
        "release": meta["score_version"], "contract_version": contract.CONTRACT_VERSION, "status": "production",
        "status_note": "the only ML output intended for the backend; everything under not_for_loading is research, demo or legacy",
        "manifest_created_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "outputs_generated_utc": {"value": iso(ranked.stat().st_mtime),
                                  "source": "file modification time of road_segments_ranked_v2.csv; the v2 forecast "
                                            "step does not record a generation timestamp"},
        "score": {"field": "blackspot_score", "definition": meta["score_definition"],
                  "units": "expected DfT severity-adjusted KSI casualties per segment, total over the two forecast years",
                  "forecast_years": meta["forecast_years"], "horizon_years": len(meta["forecast_years"]),
                  "history_years": meta["history_years"], "kind": "expected count (burden), not a per-vehicle rate",
                  "order_by": "rank (ascending); do not re-rank from the rounded CSV score"},
        "model": {"selected": spec["selected_model"], "frozen_spec_sha256": spec["sha256"],
                  "spec_frozen_on": "development folds with cutoffs 2019-2021 (data up to 2023)",
                  "production_fold": prod, "holdout_fold_already_examined": hold,
                  "saved_model_file": {"path": "ml/outputs/explainability/production_lgbm.txt",
                                       "sha256": file_hash(model_file) if model_file.exists() else None,
                                       "note": "reconstructed in Phase 2 and verified to reproduce every stored score"}},
        "network": {"segmentation": meta["segmentation"], "n_segments_scored_nationally": meta["n_segments_scored_nationally"],
                    "segment_id_stability": "stable for one OS Open Roads release and segmentation code; a new OS release can change IDs"},
        "inputs": raw,
        "files": files,
        "documentation": [f"data/v2/{d}" for d in DOCS if (V2 / d).exists()],
        "schema": "data/v2/integration_schema_v2.json",
        "not_for_loading": NOT_FOR_LOADING,
    }
    write_json(contract.spec(), V2 / "integration_schema_v2.json")
    write_json(manifest, V2 / "release_manifest_v2.json")
    print("wrote", V2 / "release_manifest_v2.json", "and", V2 / "integration_schema_v2.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
